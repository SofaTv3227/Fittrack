const DEFAULT_UNIT_GRAMS = { Stück: 50, Portion: 150 };

export const FOOD_DB = raw.map(([name, kcal, protein, carbs, fat], i) => ({
  id: `f${i}`,
  name,
  unit: 'g',
  per100: { kcal, protein, carbs, fat },
  servings: SERVING_WEIGHTS[name] || null,
}));

export function searchFoods(query, extra = []) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const all = [...extra, ...FOOD_DB];
  return all.filter((f) => f.name.toLowerCase().includes(q)).slice(0, 12);
}

// Gramm-Gewicht für eine Einheit einer bestimmten Speise (Stück/Portion),
// inkl. Fallback auf realistische Standardwerte, falls kein spezifischer Wert hinterlegt ist.
export function gramsForUnit(food, unit) {
  if (unit === 'g' || unit === 'ml') return 1;
  const specific = food?.servings?.[unit];
  return specific || DEFAULT_UNIT_GRAMS[unit] || 100;
}

export function scaleFood(food, qty, unit = 'g') {
  const grams = (qty || 0) * gramsForUnit(food, unit);
  const factor = grams / 100;
  const p = food.per100 || food;
  return {
    kcal: Math.round(p.kcal * factor),
    protein: Math.round(p.protein * factor * 10) / 10,
    carbs: Math.round(p.carbs * factor * 10) / 10,
    fat: Math.round(p.fat * factor * 10) / 10,
  };
}
